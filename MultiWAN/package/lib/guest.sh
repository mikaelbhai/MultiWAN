#!/bin/sh
# guest.sh — one-time "sign in to network" for devices on the LAN / Wi-Fi.
#
# A device that has never been seen gets no internet. Its first web request is
# redirected to a small form (the phone shows this by itself as "Sign in to
# network"). The person types a name and a mobile number, the device's MAC is
# recorded against them, and it is never asked again.
#
# How it is enforced: one nftables set of registered MACs plus two tiny chains,
# written to /etc/nftables.d so firewall4 loads them with the rest of its
# ruleset. No daemon, nothing running in the background.
#
# Sourced by api.sh for the /guests endpoints and by the portal CGI
# (/www/mwguest/cgi-bin/guest); "guest.sh apply" rebuilds the rules.

. /usr/lib/mwadmin/common.sh

G_FILE=/etc/mwadmin/guests          # mac <TAB> phone <TAB> epoch <TAB> name
G_NFT=/etc/nftables.d/20-mwguest.nft
G_PORT=8188
G_MAX=500

G_PAUSE="$MW_RUN/guest.pause"       # epoch until which sign-in is switched off for everyone

guest_enabled() { [ "$(uget mwadmin.guest.enabled)" = "1" ]; }

# Prints the time a temporary "everyone in" pause ends, or nothing when no
# pause is running. The pause lives in RAM: a reboot ends it.
guest_paused_until() {
    local t now
    t=$(cat "$G_PAUSE" 2>/dev/null)
    case "$t" in ''|*[!0-9]*) rm -f "$G_PAUSE"; return ;; esac
    now=$(date +%s)
    if [ "$t" -gt "$now" ]; then printf '%s' "$t"; else rm -f "$G_PAUSE"; fi
}

# Is the sign-in being enforced right now?
guest_active() { guest_enabled && [ -z "$(guest_paused_until)" ]; }

guest_ensure() {
    [ -f /etc/config/mwadmin ] || touch /etc/config/mwadmin
    if [ "$(uget mwadmin.guest)" != "guest" ]; then
        uci set mwadmin.guest='guest'
        uci set mwadmin.guest.enabled='0'
        uci commit mwadmin
    fi
    [ -f "$G_FILE" ] || { mkdir -p /etc/mwadmin; : > "$G_FILE"; chmod 600 "$G_FILE"; }
}

guest_valid_mac() {
    case "$1" in
        [0-9a-f][0-9a-f]:[0-9a-f][0-9a-f]:[0-9a-f][0-9a-f]:[0-9a-f][0-9a-f]:[0-9a-f][0-9a-f]:[0-9a-f][0-9a-f]) return 0 ;;
    esac
    return 1
}

# MAC of a LAN client from its IP address (empty when it is not on br-lan).
guest_mac_of() {
    local ip="${1#::ffff:}"
    ip neigh show "$ip" dev br-lan 2>/dev/null | sed -n 's/.*lladdr \([0-9a-fA-F:]\{17\}\).*/\1/p' | head -n1 | tr 'A-F' 'a-f'
}

guest_known() { grep -q "^$1	" "$G_FILE" 2>/dev/null; }

# Write the firewall include from the guest list (or remove it when off).
guest_nft_write() {
    if ! guest_active; then
        rm -f "$G_NFT"
        return
    fi
    local macs
    macs=$( { cut -f1 "$G_FILE"; cut -f1 /etc/mwadmin/exempt_devices; } 2>/dev/null | grep -E '^([0-9a-f]{2}:){5}[0-9a-f]{2}$' | sort -u | tr '\n' ',' | sed 's/,$//')
    {
        echo "# Generated by /usr/lib/mwadmin/guest.sh — do not edit."
        echo "set mw_guest_ok {"
        echo "    type ether_addr"
        [ -n "$macs" ] && echo "    elements = { $macs }"
        echo "}"
        echo "chain mw_guest_nat {"
        echo "    type nat hook prerouting priority dstnat - 10; policy accept;"
        echo "    iifname \"br-lan\" ether saddr != @mw_guest_ok fib daddr type != local meta l4proto { tcp, udp } th dport 53 redirect to :53"
        echo "    iifname \"br-lan\" ether saddr != @mw_guest_ok fib daddr type != local tcp dport 80 redirect to :$G_PORT"
        echo "}"
        echo "chain mw_guest_fwd {"
        echo "    type filter hook forward priority filter - 10; policy accept;"
        echo "    iifname \"br-lan\" ether saddr != @mw_guest_ok meta l4proto tcp reject with tcp reset"
        echo "    iifname \"br-lan\" ether saddr != @mw_guest_ok reject"
        echo "}"
    } > "$G_NFT.tmp"
    mv "$G_NFT.tmp" "$G_NFT"
}

guest_apply() {
    guest_ensure
    guest_nft_write
    # A firewall reload empties the table but keeps old chains and set members,
    # so take ours out by hand first; the reload then rebuilds them from the file.
    nft flush chain inet fw4 mw_guest_nat 2>/dev/null
    nft flush chain inet fw4 mw_guest_fwd 2>/dev/null
    nft delete chain inet fw4 mw_guest_nat 2>/dev/null
    nft delete chain inet fw4 mw_guest_fwd 2>/dev/null
    nft delete set inet fw4 mw_guest_ok 2>/dev/null
    fw4 -q reload >/dev/null 2>&1
}

# guest_add <mac> <phone> <name>   (replaces an existing entry for that MAC)
guest_add() {
    local mac="$1" phone="$2" name="$3"
    guest_valid_mac "$mac" || return 1
    guest_ensure
    lock_acquire guests 2>/dev/null
    grep -v "^$mac	" "$G_FILE" > "$G_FILE.tmp" 2>/dev/null
    printf '%s\t%s\t%s\t%s\n' "$mac" "$phone" "$(date +%s)" "$name" >> "$G_FILE.tmp"
    chmod 600 "$G_FILE.tmp"
    mv "$G_FILE.tmp" "$G_FILE"
    lock_release guests 2>/dev/null
    if guest_active; then
        guest_nft_write
        nft add element inet fw4 mw_guest_ok "{ $mac }" 2>/dev/null || fw4 -q reload >/dev/null 2>&1
    fi
    log "guest registered: $mac ($name)"
}

guest_del() {
    local mac="$1"
    guest_valid_mac "$mac" || return 1
    guest_ensure
    grep -v "^$mac	" "$G_FILE" > "$G_FILE.tmp" 2>/dev/null
    chmod 600 "$G_FILE.tmp"
    mv "$G_FILE.tmp" "$G_FILE"
    if guest_active; then
        guest_nft_write
        nft delete element inet fw4 mw_guest_ok "{ $mac }" 2>/dev/null
    fi
    log "guest removed: $mac"
}

# Keep printable text only; drop anything that could break the list file,
# JSON or HTML. $2 = max characters.
guest_clean() {
    printf '%s' "$1" | tr -d '\000-\037\177<>&"\\`|' | tr -d "'" | sed 's/^ *//; s/ *$//' | cut -c1-"${2:-40}"
}

guest_clean_phone() {
    printf '%s' "$1" | tr -cd '0-9+' | sed 's/\(.\)+/\1/g' | cut -c1-16
}

# Sign-in name: first and last name at least, letters only.
# Prints "ok <Name In Title Case>" or "err <message for the person>".
guest_check_name() {
    printf '%s' "$1" | tr -s ' \t' '  ' | awk '
    {
        n = split($0, w, " "); real = 0; out = ""
        for (i = 1; i <= n; i++) {
            x = w[i]
            if (x !~ /^[A-Za-z][A-Za-z.-]*$/) { print "err Please use English letters only in your name."; exit }
            l = tolower(x); gsub(/[.-]/, "", l)
            if (l ~ /^(test|testing|guest|user|name|admin|asdf|qwerty|abc|abcd|xyz|unknown|none|null|na|nil|my|no|fake|ok|hello|hi)$/) {
                print "err Please enter your real name."; exit }
            if (length(l) >= 2) {
                # keyboard mashing: no vowel, one letter only (aa), or the
                # same letter three times in a row (aaab)
                same = 1; run = 1; tri = 0
                for (j = 2; j <= length(l); j++) {
                    if (substr(l, j, 1) == substr(l, j - 1, 1)) { if (++run >= 3) tri = 1 }
                    else { run = 1; same = 0 }
                }
                if (l !~ /[aeiouy]/ || same || tri) { print "err Please enter your real name."; exit }
                real++
            }
            out = out (out == "" ? "" : " ") toupper(substr(x, 1, 1)) tolower(substr(x, 2))
        }
        if (real < 2) { print "err Please enter your full name: first and last name."; exit }
        if (n > 5) { print "err Please enter just your first and last name."; exit }
        print "ok " out
    }'
}

# Sign-in number: a Pakistani mobile. Accepts 0300 1234567, 3001234567,
# +92 300 1234567, 92300..., 0092300...; prints "ok 0300-1234567" or
# "err <message>". Mobile codes: 030x-034x (Jazz, Zong, Ufone, Telenor and
# Warid) and 0355 (SCO). Catches made-up numbers (0300-0000000,
# 0300-1234567, 0300-1212121); it cannot prove the SIM is real, which would
# need a code sent by SMS.
guest_check_phone() {
    local d n
    d=$(printf '%s' "$1" | tr -cd '0-9')
    case "$d" in
        00923?????????) n="0${d#0092}" ;;
        923?????????)   n="0${d#92}" ;;
        03?????????)    n="$d" ;;
        3?????????)     n="0$d" ;;
        *) echo "err Please enter a Pakistani mobile number, for example 0300 1234567 (11 digits)."; return ;;
    esac
    case "$n" in
        030*|031*|032*|033*|034*|0355*) ;;
        *) echo "err ${n%???????} is not a Pakistani mobile code. Mobile numbers start with 030 to 034, or 0355."; return ;;
    esac
    printf '%s' "${n#????}" | awk '{
        s = $0; dd = 0
        for (i = 1; i <= 7; i++) { c = substr(s, i, 1); if (!(c in seen)) { seen[c] = 1; dd++ } }
        up = "01234567890"; down = "98765432109"
        if (dd < 3 || index(up, s) || index(down, s)) exit 1
    }' || { echo "err That number does not look real. Please enter your own mobile number."; return; }
    echo "ok ${n%???????}-${n#????}"
}

# ---------------------------------------------------------------------------
# API
# ---------------------------------------------------------------------------
api_guests_get() {
    guest_ensure
    local en=0
    guest_enabled && en=1
    printf '{"ok":true,%s,%s,%s,' "$(jbool enabled "$en")" "$(jnum paused_until "$(guest_paused_until)")" "$(jnum now "$(date +%s)")"
    {
        echo "@guests"; cat "$G_FILE" 2>/dev/null
        echo "@leases"; cat /tmp/dhcp.leases 2>/dev/null
        echo "@arp";    cat /proc/net/arp 2>/dev/null
    } | awk '
        function q(s) { gsub(/\\/, "\\\\", s); gsub(/"/, "\\\"", s); gsub(/[\001-\037]/, "", s); return "\"" s "\"" }
        /^@/ { sec = $1; next }
        sec == "@guests" { n = split($0, a, "\t"); if (n >= 4) { ng++; gm[ng] = a[1]; gp[a[1]] = a[2]; gt[a[1]] = a[3]; gn[a[1]] = a[4]; known[a[1]] = 1 } next }
        sec == "@leases" && NF >= 3 { m = tolower($2); host[m] = ($4 == "*" ? "" : $4); lip[m] = $3; next }
        sec == "@arp" && $6 == "br-lan" && $3 != "0x0" { m = tolower($4); on[m] = 1; aip[m] = $1; next }
        END {
            printf "\"guests\":["
            for (i = ng; i >= 1; i--) {
                m = gm[i]
                printf "%s{\"mac\":%s,\"name\":%s,\"phone\":%s,\"ts\":%d,\"ip\":%s,\"host\":%s,\"online\":%s}", (i < ng ? "," : ""), q(m), q(gn[m]), q(gp[m]), gt[m] + 0, q((m in aip) ? aip[m] : lip[m]), q(host[m]), ((m in on) ? "true" : "false")
            }
            printf "],\"waiting\":["
            f = 1
            for (m in on) {
                if (m in known) continue
                printf "%s{\"mac\":%s,\"ip\":%s,\"host\":%s}", (f ? "" : ","), q(m), q(aip[m]), q(host[m])
                f = 0
            }
            printf "]"
        }'
    printf '}\n'
}

api_guests_set() {
    guest_ensure
    local mins
    mins=$(bodyval pause)
    case "$mins" in
        0)
            rm -f "$G_PAUSE"; guest_apply
            json_ok "$(jstr message 'Sign-in is back on.')"; return ;;
        [1-9]|[1-9][0-9]|[1-9][0-9][0-9])
            guest_enabled || { json_error "Sign-in is already off."; return; }
            echo $(( $(date +%s) + mins * 60 )) > "$G_PAUSE"; guest_apply
            log "guest sign-in paused for $mins minutes"
            json_ok "$(jstr message "Sign-in is off for everyone for $mins minutes, then it comes back by itself.")"; return ;;
    esac
    case "$(bodyval enabled)" in
        1|true)
            uci set mwadmin.guest.enabled='1'; uci commit mwadmin
            rm -f "$G_PAUSE"
            # Whoever switches it on from a LAN device should not lock that
            # device out of the page they are looking at.
            guest_apply
            json_ok "$(jstr message 'Sign-in is on. New devices must enter a name and number once.')" ;;
        0|false)
            uci set mwadmin.guest.enabled='0'; uci commit mwadmin
            guest_apply
            json_ok "$(jstr message 'Sign-in is off. Every device gets internet straight away.')" ;;
        *) json_error "Nothing to change." ;;
    esac
}

api_guests_remove() {
    local mac
    mac=$(printf '%s' "$(bodyval mac)" | tr 'A-F' 'a-f')
    guest_valid_mac "$mac" || { json_error "Unknown device."; return; }
    guest_del "$mac"
    json_ok "$(jstr message 'Removed. That device has to sign in again.')"
}

# Admin lets a device in by hand (TVs, printers: things that cannot fill a form).
api_guests_allow() {
    local mac name phone
    mac=$(printf '%s' "$(bodyval mac)" | tr 'A-F' 'a-f')
    guest_valid_mac "$mac" || { json_error "Unknown device."; return; }
    name=$(guest_clean "$(bodyval name)" 40)
    phone=$(guest_clean_phone "$(bodyval phone)")
    [ -n "$name" ] || name="Allowed by admin"
    guest_add "$mac" "$phone" "$name"
    json_ok "$(jstr message 'Device allowed.')"
}

case "${0##*/}" in
    guest.sh)
        case "$1" in
            apply) guest_apply ;;
            # Run once a minute by the mwsite watcher: ends a finished pause,
            # and restores the rules after a reboot that happened mid-pause.
            tick)
                if guest_enabled && [ -z "$(guest_paused_until)" ] && [ ! -f "$G_NFT" ]; then
                    guest_apply
                fi ;;
        esac ;;
esac
